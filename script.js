/* Scroll experience: Framer-style slow glide (Lenis) + gentle reveal + soft hero parallax. */
(function () {
  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  let lenis = null;
  if (!reduceMotion && typeof Lenis !== 'undefined') {
    lenis = new Lenis({ lerp: 0.07, smoothWheel: true });
    window.__lenis = lenis;
    const raf = (time) => { lenis.raf(time); requestAnimationFrame(raf); };
    requestAnimationFrame(raf);
    document.querySelectorAll('a[href^="#"]').forEach((link) => link.addEventListener('click', (event) => {
      const target = document.querySelector(link.getAttribute('href'));
      if (link.getAttribute('href').length > 1 && target) {
        event.preventDefault();
        lenis.scrollTo(target);
      }
    }));
  }
  if (reduceMotion) return;
  const revealTargets = document.querySelectorAll('.hero, main section, .site-footer');
  revealTargets.forEach((el) => el.classList.add('reveal'));
  /* Threshold 0 (was 0.12): the Latest Spotlights section is ~6,000px tall on phones, so it could never reach 12% visibility on a small screen and stayed invisible (opacity:0) forever. */
  if (typeof IntersectionObserver === 'undefined') {
    revealTargets.forEach((el) => el.classList.add('in'));
  } else {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('in');
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0, rootMargin: '0px 0px -40px 0px' });
    revealTargets.forEach((el) => observer.observe(el));
  }
  const magazine = document.querySelector('.open-magazine');
  if (magazine) {
    let ticking = false;
    window.addEventListener('scroll', () => {
      if (ticking) return;
      ticking = true;
      requestAnimationFrame(() => {
        const y = Math.min(window.scrollY, 600);
        magazine.style.transform = 'translateY(' + (y * 0.06) + 'px) rotate(-2deg)';
        ticking = false;
      });
    }, { passive: true });
  }
})();

